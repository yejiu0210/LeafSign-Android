        val first=Api();val second=Api(candidateThread="21",initialForum="11")
        val task=TiebaLikeTask(store,{path,fields ->
            if(fields["kw"]=="另测" || fields["kz"]=="21" || fields["thread_id"]=="21") second.call(path,fields) else first.call(path,fields)
        },{0})
        val forums=listOf(forum,otherForum)
